/** Points on an elliptical arc, angles in degrees, counterclockwise with Y up. */
export function arc(cx, cy, rx, ry, a0, a1, step = 22) {
  const n = Math.max(3, Math.round(Math.abs(a1 - a0) / step));
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    out.push([Math.round(cx + rx * Math.cos(a)), Math.round(cy + ry * Math.sin(a))]);
  }
  return out;
}

const dot = (x, y, w = 1.3) => ({ pts: [[x, y], [x + 3, y + 6]], w });
const mirrorX = (strokes, width) => strokes.map((s) => (Array.isArray(s) ? s : s.pts).map(([x, y]) => [width - x, y]));

