// Builds the browser bundle used by the editor app (docs/app/) and the
// embeddable drawing widget (docs/app/embed.mjs): the core engine and the
// handwriting scanner as one ES module at docs/app/lib/fontsketch.mjs.
// The app's own modules in docs/app/js/ are served as they are.
// Usage: npm run docs:app        (add --watch to rebuild on change)
import { build, context } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = join(root, 'docs', 'app', 'lib');
mkdirSync(out, { recursive: true });

const lines = ["export * from '../src/core/index.mjs';"];
// Geometry helpers the editor needs. While the core index does not expose one
// of them (or still exposes a placeholder), take it from geometry.mjs.
const index = readFileSync(join(root, 'src', 'core', 'index.mjs'), 'utf8');
const geometry = readFileSync(join(root, 'src', 'core', 'geometry.mjs'), 'utf8');
const wanted = ['fitContour', 'strokeToOutline', 'removeOverlaps', 'correctDirection', 'simplify', 'fitCurves', 'cubicToQuadratic', 'contourArea', 'bounds', 'pathFromPoints', 'circleContour'];
const has = (src, re) => new RegExp(re).test(src);
const direct = wanted.filter((n) => has(geometry, `export function ${n}\\b`) && (!has(index, `\\b${n}\\b`) || has(index, `pending\\('${n}'\\)`)));
if (direct.length) lines.push(`export { ${direct.join(', ')} } from '../src/core/geometry.mjs';`);
if (existsSync(join(root, 'src', 'scan', 'index.mjs'))) lines.push("export * as scan from '../src/scan/index.mjs';");
const entryDir = join(root, 'tmp');
mkdirSync(entryDir, { recursive: true });
const entry = join(entryDir, 'app-entry.mjs');
writeFileSync(entry, `// Generated by scripts/build-docs.mjs\n${lines.join('\n')}\n`);

const options = {
  entryPoints: [entry],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2020', 'safari14'],
  minify: true,
  legalComments: 'none',
  outfile: join(out, 'fontsketch.mjs'),
  banner: { js: '/*! fontsketch engine for the editor app | MIT | https://github.com/kwy404/fontsketch */' },
  logLevel: 'warning',
};

if (process.argv.includes('--watch')) {
  const ctx = await context(options);
  await ctx.watch();
  console.log('docs:app watching src/ for changes');
} else {
  await build(options);
  const kb = (statSync(options.outfile).size / 1024).toFixed(1);
  console.log(`docs:app wrote docs/app/lib/fontsketch.mjs (${kb} KB)`);
}
